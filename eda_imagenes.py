import numpy as np
import matplotlib.pyplot as plt
import matplotlib.colors

# Definir las nuevas etiquetas y los rangos de NDWI
# Considerando que "con agua" puede ser "agua" y "sin agua" puede ser "no agua"
etiquetas_agua_no_agua = {
    'agua': (0.5, 1.0), # Umbral ajustado a 0.5
    'no agua': (-1.0, 0.5) # El rango de no agua se ajusta para no superponerse con agua
}

# Crear una matriz vacía para almacenar las nuevas etiquetas
etiquetas_roi_agua_no_agua = np.empty(ndwi_manual_roi_image.shape, dtype=object)

# Iterar sobre cada píxel en la ROI y asignar una etiqueta
for i in range(etiquetas_roi_agua_no_agua.shape[0]):
    for j in range(etiquetas_roi_agua_no_agua.shape[1]):
        ndwi_valor = ndwi_manual_roi_image[i, j]

        etiqueta_asignada = 'Desconocido' # Etiqueta por defecto

        for etiqueta, (min_val, max_val) in etiquetas_agua_no_agua.items():
            if min_val <= ndwi_valor < max_val: # Usamos < max_val para evitar superposiciones en los límites
                etiqueta_asignada = etiqueta
                break
            # Manejar el caso del límite superior explícitamente si max_val es 1.0
            if etiqueta == 'agua' and max_val == 1.0 and ndwi_valor == 1.0:
                 etiqueta_asignada = etiqueta
                 break


        etiquetas_roi_agua_no_agua[i, j] = etiqueta_asignada

print("Etiquetado de píxeles en la ROI con categorías agua/no agua completado (umbral 0.2).")

# --- Visualización de la ROI etiquetada ---

# Necesitamos mapear las etiquetas a valores numéricos para visualizar
etiquetas_unicas_agua_no_agua = list(etiquetas_agua_no_agua.keys())
num_etiquetas_agua_no_agua = len(etiquetas_unicas_agua_no_agua)
etiqueta_a_numero_agua_no_agua = {etiqueta: i for i, etiqueta in enumerate(etiquetas_unicas_agua_no_agua)}

# Crear una matriz numérica a partir de las nuevas etiquetas de la ROI
etiquetas_numericas_roi_agua_no_agua = np.zeros(etiquetas_roi_agua_no_agua.shape, dtype=int)
for i in range(etiquetas_roi_agua_no_agua.shape[0]):
    for j in range(etiquetas_roi_agua_no_agua.shape[1]):
        etiqueta = etiquetas_roi_agua_no_agua[i, j]
        if etiqueta in etiqueta_a_numero_agua_no_agua:
            etiquetas_numericas_roi_agua_no_agua[i, j] = etiqueta_a_numero_agua_no_agua[etiqueta]
        else:
             etiquetas_numericas_roi_agua_no_agua[i, j] = -1 # Para etiquetas desconocidas


# Definir los colores para cada nueva etiqueta
colores_agua_no_agua = plt.cm.get_cmap('Blues', num_etiquetas_agua_no_agua) # Usamos un colormap que sugiere agua

# Crear una lista de ticks para la barra de color
ticks_agua_no_agua = [i for i in range(num_etiquetas_agua_no_agua)]

# Visualizar la imagen con las nuevas etiquetas
plt.figure(figsize=(8, 8))
plt.imshow(etiquetas_numericas_roi_agua_no_agua, cmap=colores_agua_no_agua)
cbar_agua_no_agua = plt.colorbar(ticks=ticks_agua_no_agua)
cbar_agua_no_agua.ax.set_yticklabels(etiquetas_unicas_agua_no_agua) # Establecer las etiquetas de la barra de color
plt.title('ROI Etiquetada: Agua vs No Agua (NDWI con umbral 0.5)')
plt.xlabel('Píxeles (columnas)')
plt.ylabel('Píxeles (filas)')
plt.show()